"""
X-5 regression tests: the Alembic chain must build a complete, correct schema
from a genuinely empty database using nothing but `alembic upgrade head` — no
Base.metadata.create_all(), no stamping.

Before the genesis migration (6b66f0fdb4f3) existed, every test in this file
would fail: `alembic upgrade head` on an empty database raised
`UndefinedTableError: relation "investigation_cases" does not exist` at
revision cba64ddf4a02, because the five earliest migrations
(f070db4817a2, cba64ddf4a02, 24d74fa147f3, 2331ec567cbb, 8532d6f9c999) were
generated by diffing an already-populated database and never contained the
DDL to create the foundational tables they assume exist. See
docs/MIGRATION_REMEDIATION_PROPOSAL.md and 6b66f0fdb4f3's own docstring for
the full account.
"""
import asyncio

import pytest
from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

import models  # noqa: F401
from models.base import Base
from scripts.migrate import alembic_config as scripts_alembic_config
from tests.test_migrations import MIGRATION_DB, _alembic_config, _drop_database, _recreate_database, _url_for

GENESIS_DB = MIGRATION_DB  # reuse test_migrations.py's isolated throwaway database; tests run sequentially


def _run_upgrade_to(database_url: str, target: str) -> None:
    """Runs synchronously (in a worker thread) because alembic's env.py calls asyncio.run."""
    command.upgrade(_alembic_config(database_url), target)


async def _diff_and_version(database_url: str):
    engine = create_async_engine(database_url, poolclass=NullPool)
    try:
        async with engine.connect() as conn:
            def work(sync_conn):
                diffs = compare_metadata(MigrationContext.configure(sync_conn), Base.metadata)
                return diffs
            diffs = await conn.run_sync(work)
            version = (await conn.execute(text("SELECT version_num FROM alembic_version"))).scalar_one()
        return diffs, version
    finally:
        await engine.dispose()


@pytest.mark.asyncio
async def test_alembic_upgrade_head_builds_a_genuinely_empty_database():
    """
    The core X-5 regression test. Pure `alembic upgrade head` (command.upgrade,
    not scripts.migrate.bootstrap, not create_all) against a database with zero
    tables and no alembic_version row must succeed end to end and produce a
    schema with zero differences from the live ORM models.
    """
    db_url = _url_for(GENESIS_DB, "postgresql+asyncpg")
    await _recreate_database(GENESIS_DB)
    try:
        await asyncio.to_thread(_run_upgrade_to, db_url, "head")

        diffs, version = await _diff_and_version(db_url)
        script_head = ScriptDirectory.from_config(_alembic_config(db_url)).get_current_head()

        assert version == script_head
        assert diffs == [], f"migrated schema differs from ORM models: {diffs}"
    finally:
        await _drop_database(GENESIS_DB)


def test_genesis_is_the_sole_root_and_the_chain_to_head_is_linear():
    """
    Structural safety net: exactly one revision has down_revision=None (the
    genesis migration), and there is exactly one head. A second orphan root,
    or a branch, would mean alembic upgrade head no longer reliably reaches a
    single, predictable schema from empty.
    """
    script_dir = ScriptDirectory.from_config(scripts_alembic_config())
    bases = list(script_dir.get_bases())
    heads = list(script_dir.get_heads())

    assert bases == ["6b66f0fdb4f3"], f"expected exactly one root (the genesis migration), got {bases}"
    assert len(heads) == 1, f"expected exactly one head, got {heads}"

    # Walk from head back to base and confirm every revision in the repo is on that
    # single path (no orphaned or branched revision files sitting unreferenced).
    revisions_on_path = {r.revision for r in script_dir.walk_revisions(base="base", head=heads[0])}
    all_revisions = {r.revision for r in script_dir.walk_revisions()}
    assert revisions_on_path == all_revisions


@pytest.mark.asyncio
async def test_database_stamped_exactly_at_genesis_upgrades_cleanly_through_full_chain():
    """
    A database that only ever ran the genesis migration (e.g. an install that
    adopted this fix from day one) must still reach an identical, zero-diff
    schema when the rest of the chain runs — proving genesis's downstream
    compatibility with every migration after it, not just the empty-DB case.
    """
    db_url = _url_for(GENESIS_DB, "postgresql+asyncpg")
    await _recreate_database(GENESIS_DB)
    try:
        await asyncio.to_thread(_run_upgrade_to, db_url, "6b66f0fdb4f3")

        diffs_at_genesis, version_at_genesis = await _diff_and_version(db_url)
        assert version_at_genesis == "6b66f0fdb4f3"
        assert diffs_at_genesis, "genesis alone must not already match full ORM metadata (sanity check the test itself)"

        await asyncio.to_thread(_run_upgrade_to, db_url, "head")

        diffs, version = await _diff_and_version(db_url)
        script_head = ScriptDirectory.from_config(_alembic_config(db_url)).get_current_head()
        assert version == script_head
        assert diffs == []
    finally:
        await _drop_database(GENESIS_DB)
